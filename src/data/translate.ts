function applyPairs(input: string, pairs: [string, string][]): string {
  const ordered = [...pairs].sort((a, b) => b[0].length - a[0].length || a[0].localeCompare(b[0]));
  let s = input;
  for (const [jp, zh] of ordered) {
    if (jp && s.includes(jp)) s = s.split(jp).join(zh);
  }
  return s;
}

function toTraditional(input: string): string {
  let out = "";
  for (const ch of input) out += GLYPH[ch] ?? ch;
  return out;
}

export function localizeJp(input: string): string {
  if (!input) return "";
  let s = input.replace(/▲/g, "↑").replace(/▼/g, "↓").replace(/◆/g, "").replace(/◇/g, "※ ");
  s = s.replace(/（/g, "(").replace(/）/g, ")");
  s = applyPairs(s, [...GRAMMAR, ...PHRASES]);
  s = toTraditional(s);
  s = s.replace(/，、/g, "，").replace(/。。/g, "。");
  s = s.replace(/\s+/g, " ").trim();
  s = s.replace(/\(\s+/g, "(").replace(/\s+\)/g, ")");
  return s;
}

export function translateLabel(label: string): string {
  if (!label) return "";
  return localizeJp(label);
}

export function translateValue(value: string): string {
  if (!value) return "";
  return localizeJp(value);
}

export function translateArea(area: string): string {
  if (!area) return "";
  return localizeJp(area).replace(/可旋轉 可旋轉/g, "可旋轉");
}

export function translateCat(cat: string): string {
  return CATS[cat] ?? localizeJp(cat);
}

export function translateDesc(desc: string): string {
  return localizeJp(desc.replace(/<br\s*\/?>/gi, " ").replace(/<[^>]+>/g, " "));
}

const SKIP_EFFECT = new Set(["効果時間", "時長"]);

export function isDurationEffectLabel(label: string): boolean {
  return SKIP_EFFECT.has(label);
}
